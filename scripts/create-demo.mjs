import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createApp } from '../src/server.js';

// Presentation capture uses an isolated in-memory database; no real accounts are read.
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/jayni/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright-core');
const out = resolve('data/demo');
await mkdir(out, { recursive: true });
const { server, db } = createApp({ databasePath: ':memory:' });
await new Promise(r => server.listen(0, '127.0.0.1', r));
const origin = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const shot = async name => { await page.waitForTimeout(450); await page.screenshot({ path: resolve(out, `${name}.png`) }); console.log(`Captured ${name}`); };
  await page.goto(origin);
  await page.locator('#auth-submit').waitFor();
  await shot('01-welcome');
  await page.locator('#auth-form input[name=name]').fill('Demo Listener');
  await page.locator('input[name=email]').fill('demo@example.test');
  await page.locator('input[name=password]').fill('DemoOnly-October2026');
  await page.locator('#auth-submit').click();
  await page.locator('#app-view').waitFor({ state: 'visible' });
  await shot('02-dashboard');
  await page.locator('#preferences-button').click();
  await page.getByRole('button', { name: 'Save preferences', exact: true }).waitFor();
  await page.locator('.pref-all-grid').getByRole('button', { name: 'Add Bollywood', exact: true }).click();
  await page.locator('.pref-nav-item').filter({ hasText: 'Artists' }).click();
  await page.locator('.pref-all-grid').getByRole('button', { name: 'Add Arijit Singh', exact: true }).click();
  await page.locator('.pref-nav-item').filter({ hasText: 'Languages' }).click();
  await page.locator('.pref-all-grid').getByRole('button', { name: 'Add Hindi', exact: true }).click();
  await shot('03-preferences');
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await page.locator('#preferences-dialog').waitFor({ state: 'hidden' });
  await page.locator('#moods button').filter({ hasText: 'Romantic' }).click();
  await page.locator('#activities button').filter({ hasText: 'Driving' }).click();
  await page.locator('#context').scrollIntoViewIfNeeded();
  await shot('04-context');
  const responseBefore = page.waitForResponse(r => r.url().endsWith('/api/recommendations') && r.request().method() === 'POST');
  await page.locator('#generate').click();
  const before = await (await responseBefore).json();
  await page.locator('#results .song-row').first().waitFor();
  await page.locator('#results-section').evaluate(e => e.scrollIntoView({ block: 'start', behavior: 'instant' }));
  await shot('05-results');
  await page.locator('#results .song-row').first().locator('summary').click();
  await shot('06-explanation');
  await page.locator('#results .rate-button').first().click();
  await page.locator('#rating-form select[name=score]').selectOption('5');
  await page.locator('#rating-form select[name=helpful]').selectOption('1');
  await page.locator('#rating-form textarea').fill('A good fit for this romantic drive.');
  await shot('07-rating');
  const responseAfter = page.waitForResponse(r => r.url().endsWith('/api/recommendations') && r.request().method() === 'POST');
  await page.locator('#rating-form button.primary').click();
  const after = await (await responseAfter).json();
  await page.locator('#rating-dialog').waitFor({ state: 'hidden' });
  await page.locator('#results .song-row').first().locator('summary').click();
  await shot('08-feedback');
  await page.locator('#save-mix').click();
  await page.locator('#save-form input[name=name]').fill('Romantic drive');
  await shot('09-save');
  await page.locator('#save-form button.primary').click();
  await page.locator('#save-dialog').waitFor({ state: 'hidden' });
  await page.locator('[data-view=mixes]').click();
  await page.locator('#mixes-view').waitFor({ state: 'visible' });
  await shot('10-mixes');
  await page.locator('[data-view=history]').click();
  await page.locator('#history-view').waitFor({ state: 'visible' });
  await shot('11-history');
  await page.locator('[data-view=catalog]').click();
  await page.locator('#catalog-view').waitFor({ state: 'visible' });
  await shot('12-catalog');
  const trackId = before.songs[0].id;
  const beforeTrack = before.songs.find(s => s.id === trackId);
  const afterTrack = after.songs.find(s => s.id === trackId);
  if (!(afterTrack.score > beforeTrack.score)) throw new Error('Feedback did not increase the selected track score');
  await writeFile(resolve(out, 'demo-evidence.json'), JSON.stringify({ capturedAt: new Date().toISOString(), isolatedDatabase: true, errors, before: beforeTrack, after: afterTrack, resultCount: before.songs.length }, null, 2));
  if (errors.length) throw new Error(errors.join('; '));
  await writeFile(resolve(out, 'probe.json'), JSON.stringify({ origin, errors, media: await page.evaluate(() => ['video/mp4;codecs=avc1.42E01E,mp4a.40.2','video/webm;codecs=vp9,opus','video/webm'].map(type => [type,MediaRecorder.isTypeSupported(type)])) }, null, 2));
} finally {
  await browser?.close();
  await new Promise(r => server.close(r));
  await db.close();
}
